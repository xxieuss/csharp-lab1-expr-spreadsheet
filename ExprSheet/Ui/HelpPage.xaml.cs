namespace Ui;

public partial class HelpPage : ContentPage {
    public HelpPage() {
        InitializeComponent();
        ShowSyntaxHelp();
    }

    private void OnSyntax(object? sender, EventArgs e) => ShowSyntaxHelp();
    private void OnOperations(object? sender, EventArgs e) => ShowOperationsHelp();
    private void OnLanguage(object? sender, EventArgs e) => ShowLanguageHelp();
    private void OnFiles(object? sender, EventArgs e) => ShowFilesHelp();

    public void ShowSyntaxHelp() {
        TextLabel.Text = """
            ЯК ЗАПОВНЮВАТИ ТАБЛИЦЮ

            Натисніть на клітинку – її вміст з'явиться в рядку формул угорі. Введіть вираз і натисніть Enter. Виділення перейде на клітинку нижче, тому стовпець зручно заповнювати підряд.

            З ЧОГО СКЛАДАЄТЬСЯ ВИРАЗ

            Цілі числа довільної довжини: 12345678901234567890. Обмежень на кількість цифр немає.

            Посилання на клітинки: A1, B12, AA7. Літери задають стовпець, цифри — рядок. Регістр не має значення, a1 і A1 — та сама клітинка.

            Круглі дужки для зміни порядку дій: (2 + 3) * 4.

            Пробіли між лексемами можна ставити будь-де: A1+2 і A1 + 2 рівнозначні.

            ДВА ЕТАПИ ОБРОБКИ

            Спочатку перевіряється синтаксис. Якщо вираз записано неправильно, під рядком формул з'являється повідомлення з позицією помилки, і обчислення не починається.

            Далі вираз обчислюється. На цьому етапі можливі інші помилки: ділення на нуль, циклічне посилання, невідповідність типів. Клітинка з помилкою показує слово ПОМИЛКА, а причина видно в рядку формул, коли клітинку обрано.

            РЕЖИМИ ВІДОБРАЖЕННЯ

            Кнопка ВИРАЗ / ЗНАЧЕННЯ перемикає те, що показано в клітинках: початковий текст або обчислений результат. На введення режим не впливає.

            РОЗМІР ТАБЛИЦІ

            Кнопки зі знаками плюс і мінус додають та видаляють рядки й стовпці. Останній рядок і останній стовпець видалити не можна.
            """;
    }

    public void ShowOperationsHelp() {
        TextLabel.Text = """
            ОПЕРАЦІЇ ВАРІАНТА 33

            Від найнижчого пріоритету до найвищого:

            not — логічне заперечення
            <=  >=  <> — порівняння
            +  - — додавання і віднімання
            *  / — множення і ділення
            ^ — піднесення до степеня
            +  - — унарні плюс і мінус

            ЩО ВАЖЛИВО ЗНАТИ

            Степінь правоасоціативний: 2 ^ 3 ^ 2 означає 2 ^ (3 ^ 2) і дорівнює 512, а не 64.

            Ділення цілочислове: 7 / 2 дає 3. Ділення на нуль — помилка обчислення.

            Порівняння не можна записувати ланцюжком: A1 <= B1 <= C1 є синтаксичною помилкою.

            ЧИСЛА Й ЛОГІЧНІ ЗНАЧЕННЯ

            Значення клітинки буває або цілим числом, або логічним: Істина чи Хиба.

            Арифметичні операції приймають числа. Порівняння приймають числа й дають логічне значення. Операція not приймає логічне значення.

            Тому 1 + (A1 <= 2) — помилка обчислення: до числа додається логічне значення. А not (A1 <= 2) — правильний вираз.

            Операція <> порівнює і числа, і логічні значення.
            """;
    }

    public void ShowLanguageHelp() {
        TextLabel.Text = """
            СПРОЩЕНА МОВА

            Крім виразу, у клітинці можна записати оператор.

            ПРИСВОЄННЯ

            B3 := A1 + 5

            Клітинка обчислює вираз і записує результат у вказану клітинку. Сама клітинка показує те саме значення.

            Присвоєння дозволене лише на початку вмісту клітинки. Усередині виразу це синтаксична помилка.

            Клітинка-адресат не повинна мати власного вмісту, і двоє присвоєнь не можуть писати в ту саму клітинку.

            УМОВНИЙ ОПЕРАТОР

            if A1 <= 10 then 100

            Якщо умова істинна, клітинка набуває значення виразу після then. Якщо хибна, клітинка лишається порожньою. Гілки else немає.

            Умовні оператори можна вкладати: if A1 <= 10 then if B1 <= 5 then 1

            ЧОМУ ПІСЛЯ then НЕ МОЖНА ПРИСВОЮВАТИ

            Запис if A1 <= 10 then B5 := 1 відхиляється як синтаксична помилка.

            Порядок обчислення клітинок задає граф залежностей, який будується до обчислення. Якщо адресат запису залежить від умови, він став би відомий лише під час обчислення — коли порядок уже визначено. Тому таке присвоєння заборонене.
            """;
    }

    public void ShowFilesHelp() {
        TextLabel.Text = """
            ЗБЕРЕЖЕННЯ ТА ВІДКРИТТЯ

            Таблиця зберігається у форматі JSON. У файл потрапляє вміст клітинок, а не обчислені значення, тому після відкриття все перераховується заново.

            Кнопка «Нова» очищає таблицю.

            НА КОМП'ЮТЕРІ

            «Зберегти» запитує назву файлу, «Відкрити» показує вікно вибору файлу.

            НА GOOGLE DRIVE

            «Drive: зберегти» і «Drive: відкрити» працюють за назвою файлу. Якщо файл із такою назвою вже існує, він оновлюється, інакше створюється новий.

            Під час першого звернення відкриється браузер із запитом дозволу. Після згоди дозвіл зберігається на цьому комп'ютері, і надалі його не питатимуть.

            Програма бачить на Google Drive лише ті файли, які створила сама. До решти вашого диска доступу вона не має.
            """;
    }
