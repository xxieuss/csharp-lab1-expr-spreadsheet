namespace Ui;

public partial class HelpPage : ContentPage {
    public HelpPage() {
        InitializeComponent();
        ShowSyntaxHelp();
    }

    private void OnSyntax(object? sender, EventArgs e) => ShowSyntaxHelp();
    private void OnOperations(object? sender, EventArgs e) => ShowOperationsHelp();
    private void OnLanguage(object? sender, EventArgs e) => ShowLanguageHelp();

    public void ShowSyntaxHelp() {
        TextLabel.Text =
            """
            ВМІСТ КЛІТИНКИ

            У клітинку записується вираз із цілих чисел, посилань на інші клітинки
            та операцій. Числа цілі, довільної довжини – обмеження на кількість
            цифр немає.

            ПОСИЛАННЯ НА КЛІТИНКУ

            Літери стовпця і номер рядка: A1, C7, AB12. Регістр не важливий,
            a1 і A1 — та сама клітинка.

            Посилання вказує на ПОЗИЦІЮ. Якщо вставити або видалити рядок чи
            стовпець, клітинки зсунуться, і формула почне читати те, що опинилось
            за цією адресою. Формули при цьому не переписуються.

            Посилання на порожню клітинку — помилка, а не нуль. Так одразу видно,
            що формула дивиться не туди.

            ДУЖКИ Й ПРОПУСКИ

            Круглі дужки змінюють порядок обчислення. Пропуски між лексемами можна
            ставити будь-де: 2+2 і 2 + 2 однакові.

            РЕЖИМИ ВІДОБРАЖЕННЯ

            ЗНАЧЕННЯ — у клітинках показані обчислені результати.
            ВИРАЗ — показано те, що введено.
            Перемикач угорі вікна.

            ПОМИЛКИ

            Обробка виконується у два етапи. Спершу перевіряється синтаксис: якщо
            вираз записаний неправильно, під рядком формул з'явиться повідомлення
            з номером позиції символу, на якому розбір зупинився.

            Лише після успішної перевірки вираз обчислюється, і там можливі свої
            помилки: ділення на нуль, невідповідність типів, циклічне посилання,
            звернення до порожньої клітинки або за межі таблиці.
            """;
    }

    public void ShowOperationsHelp() {
        TextLabel.Text =
            """
            ОПЕРАЦІЇ

            Від найслабшого пріоритету до найсильнішого:

               not                логічне заперечення
               <=   >=   <>       порівняння
               +    -             додавання і віднімання
               *    /             множення і ділення
               ^                  піднесення до степеня
               +    -             унарні плюс і мінус

            ЩО ВАРТО ЗНАТИ

            Ділення цілочислене: 7 / 2 дає 3.

            Степінь правоасоціативний: 2 ^ 3 ^ 2 означає 2 ^ (3 ^ 2) = 512.

            Унарний мінус сильніший за степінь, як в Excel: -2 ^ 2 дає 4, а не -4.

            Порівняння не можна складати в ланцюжок: A1 <= B1 <= C1 є синтаксичною
            помилкою.

            Операції <= і >= працюють лише з числами. Операція <> порівнює і числа,
            і логічні значення.

            Значення клітинки може бути числом або логічним (Істина, Хиба), бо
            вирази варіанта 33 логічні.

            Показник степеня має бути невід'ємним і не більшим за 100000: інакше
            результат не буде цілим числом або не вміститься в пам'ять.

            ПРИКЛАДИ

               (A1 + A2) * 2 <= 30
               not A1 <= 100
               2 ^ 200
               A1 <> A2
            """;
    }

    public void ShowLanguageHelp() {
        TextLabel.Text =
            """
            ОПЕРАТОРИ СПРОЩЕНОЇ МОВИ

            Крім виразу, у клітинку можна записати оператор.

            УМОВНИЙ ОПЕРАТОР

               if <умова> then <вираз>

            Якщо умова істинна, клітинка отримує значення того, що стоїть після
            then. Якщо хибна — клітинка лишається порожньою.

               if A1 <= 10 then A1 * 2

            Умовні оператори можна вкладати:

               if A1 <= 10 then if A2 <= 5 then A1 + A2

            ПРИСВОЄННЯ

               <клітинка> := <вираз>

            Клітинка з таким оператором обчислює вираз і записує результат у
            вказану клітинку. Власне значення теж дорівнює цьому результату.

               A5 := A1 + A2

            Правила:

               - цільова клітинка має бути порожньою, власного вмісту в неї бути
                 не може;
               - у ту саму клітинку не можуть писати дві різні клітинки;
               - клітинка не може присвоювати сама собі;
               - присвоєння може стояти лише на початку вмісту клітинки, усередині
                 if його бути не може.

            Остання заборона не випадкова: порядок перерахунку будується до
            обчислення, а всередині if ціль запису залежала б від умови, яка на
            той момент ще не відома.

            Коли клітинку заповнено присвоєнням ззовні, у режимі ВИРАЗ вона
            порожня, а в режимі ЗНАЧЕННЯ показує отримане значення.
            """;
    }
}